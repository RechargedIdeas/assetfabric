"""PWAPipeline — Web export orchestrator (SPEC §3 Layer A): size budget, COOP/COEP, offline SW, smoke tests.

Input is Godot's own Web export with its PWA option on (``progressive_web_app/*`` in the ``web`` preset:
service worker, manifest, offline page, ``ensure_cross_origin_isolation_headers``). The pipeline then

1. patches ``index.html`` with a tiny opt-in hook so QA can pass engine args via the URL *fragment*
   (``#fabric-args=<url-encoded JSON array>``; fragments never reach the server or the SW cache key),
2. writes host header configs (``_headers`` for Netlify / Cloudflare Pages style hosts; nginx snippet in
   docs/packaging.md) that send COOP ``same-origin`` + COEP ``require-corp``,
3. gates **G-WEB-01**: gzip-9 compressed payload < 45 MB; every runtime file is in the SW cache lists,
4. smoke-tests in headless Chrome (Playwright driving the system Chrome, SwiftShader WebGL2) against a
   local server: response headers present, ``crossOriginIsolated``, SW registered, game boots, the
   wasm/pck land in the SW cache, an **offline reload** boots from cache, and a header-less host still
   reaches isolation through the SW header shim.
"""

from __future__ import annotations

import functools
import gzip
import http.server
import json
import re
import threading
import time
import urllib.parse
from pathlib import Path
from typing import Any

BUDGET_BYTES = 45_000_000          # G-WEB-01 "<45 MB compressed" — decimal MB (stricter than MiB) [INFERENCE F7-4]
HOOK_MARK = "/* fabric-args hook (PWAPipeline) */"
HOOK = (HOOK_MARK + " (function(){var m=location.hash.match(/fabric-args=([^&]*)/);if(m){try{"
        "GODOT_CONFIG.args=GODOT_CONFIG.args.concat(JSON.parse(decodeURIComponent(m[1])));}catch(e){console.error(e);}}})();")
HEADERS = {"Cross-Origin-Opener-Policy": "same-origin", "Cross-Origin-Embedder-Policy": "require-corp"}
RUNTIME_FILES = ["index.html", "index.js", "index.wasm", "index.pck", "index.worker.js", "index.audio.worklet.js",
                 "index.offline.html"]
HEADERS_FILE = """# Host headers for Game Zero Web (Netlify / Cloudflare Pages `_headers` format). Generated by PWAPipeline.
/*
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Embedder-Policy: require-corp
/index.service.worker.js
  Cache-Control: no-cache
/index.html
  Cache-Control: no-cache
"""


def web_dir(root: Path) -> Path:
    return root / "dist" / "web"


def patch_html(d: Path) -> bool:
    p = d / "index.html"
    html = p.read_text(encoding="utf-8")
    if HOOK_MARK in html:
        return True
    m = re.search(r"const GODOT_CONFIG = \{.*?\};\n", html)
    if not m:
        return False
    p.write_text(html[:m.end()] + HOOK + "\n" + html[m.end():], encoding="utf-8")
    return True


def budget(d: Path) -> dict[str, Any]:
    files = {}
    for p in sorted(d.iterdir()):
        if p.is_file() and p.name not in ("BUILD.json",):
            raw = p.read_bytes()
            files[p.name] = {"bytes": len(raw), "gzip9": len(gzip.compress(raw, compresslevel=9))}
    total_gz = sum(f["gzip9"] for f in files.values())
    total = sum(f["bytes"] for f in files.values())
    return {"budget_bytes": BUDGET_BYTES, "total_bytes": total, "total_gzip9": total_gz, "ok": total_gz < BUDGET_BYTES,
            "headroom_bytes": BUDGET_BYTES - total_gz, "files": files}


def sw_report(d: Path) -> dict[str, Any]:
    sw = (d / "index.service.worker.js").read_text(encoding="utf-8")
    def arr(name: str) -> list[str]:
        m = re.search(rf"const {name} = (\[.*?\]);", sw)
        return json.loads(m.group(1)) if m else []
    cached, cachable = arr("CACHED_FILES"), arr("CACHABLE_FILES")
    full = set(cached) | set(cachable)
    missing = [f for f in RUNTIME_FILES if f not in full]
    man = json.loads((d / "index.manifest.json").read_text(encoding="utf-8")) if (d / "index.manifest.json").exists() else {}
    return {"cached_on_install": cached, "cached_on_first_use": cachable, "runtime_missing_from_cache": missing,
            "ensure_isolation_shim": "ENSURE_CROSSORIGIN_ISOLATION_HEADERS = true" in sw,
            "manifest": {k: man.get(k) for k in ("name", "start_url", "display", "orientation")} | {"icons": len(man.get("icons", []))},
            "ok": not missing and bool(man.get("start_url")) and bool(man.get("icons"))}


# --------------------------------------------------------------------------- local server + headless Chrome

class _Handler(http.server.SimpleHTTPRequestHandler):
    send_isolation = True
    seen: list[dict[str, Any]] = []

    def end_headers(self) -> None:
        if self.send_isolation:
            for k, v in HEADERS.items():
                self.send_header(k, v)
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()

    def log_message(self, *a: Any) -> None:  # quiet
        pass

    def guess_type(self, path: Any) -> str:
        return "application/wasm" if str(path).endswith(".wasm") else super().guess_type(path)


class LocalHost:
    """Static server for dist/web with or without COOP/COEP (simulates a header-less host)."""

    def __init__(self, d: Path, isolation: bool = True):
        h = type("H", (_Handler,), {"send_isolation": isolation})
        srv_cls = type("S", (http.server.ThreadingHTTPServer,), {"handle_error": lambda self, req, addr: None})
        self.srv = srv_cls(("127.0.0.1", 0), functools.partial(h, directory=str(d)))   # quiet on client resets
        self.thread = threading.Thread(target=self.srv.serve_forever, daemon=True)

    def __enter__(self) -> "LocalHost":
        self.thread.start()
        return self

    def __exit__(self, *a: Any) -> None:
        self.srv.shutdown()
        self.srv.server_close()

    @property
    def url(self) -> str:
        return f"http://127.0.0.1:{self.srv.server_address[1]}/"


def head_headers(url: str) -> dict[str, str]:
    import urllib.request

    with urllib.request.urlopen(url, timeout=10) as r:     # noqa: S310 (localhost)
        return {k: v for k, v in r.headers.items() if k.lower().startswith("cross-origin")}


class WebHarness:
    """One persistent headless-Chrome profile (IndexedDB + SW cache survive between runs)."""

    def __init__(self, chrome: str | None = None):
        from forge.packaging import chrome_path

        self.chrome = chrome or chrome_path()
        self._pw = self._browser = self.ctx = None

    def __enter__(self) -> "WebHarness":
        from playwright.sync_api import sync_playwright

        self._pw = sync_playwright().start()
        self._browser = self._pw.chromium.launch(executable_path=self.chrome, headless=True,
                                                 args=["--use-angle=swiftshader", "--enable-unsafe-swiftshader",
                                                       "--ignore-gpu-blocklist", "--autoplay-policy=no-user-gesture-required"])
        self.ctx = self._browser.new_context()
        return self

    def __exit__(self, *a: Any) -> None:
        if self._browser:
            self._browser.close()
        if self._pw:
            self._pw.stop()

    def run(self, base_url: str, args: list[str] | None = None, *, wait_for: str = "FABRIC_RESULT", timeout_s: float = 90,
            offline: bool = False, settle_sw: bool = False, linger_ms: int = 1500) -> dict[str, Any]:
        from forge.milestones import parse_output

        if args and args[0] != "--":
            args = ["--", *args]          # engine argv: user args follow "--" (OS.get_cmdline_user_args)
        url = base_url + "index.html" + ("#fabric-args=" + urllib.parse.quote(json.dumps(args)) if args else "")
        page = self.ctx.new_page()
        logs: list[str] = []
        page.on("console", lambda m: logs.append(m.text))
        self.ctx.set_offline(offline)
        t0 = time.time()
        err = None
        try:
            page.goto(url, wait_until="load", timeout=int(timeout_s * 1000))
            while time.time() - t0 < timeout_s and not any(wait_for in ln for ln in logs):
                page.wait_for_timeout(250)
            page.wait_for_timeout(linger_ms)     # let Godot's IDBFS sync (user://) finish before the page closes
            info = page.evaluate("""async () => {
                const reg = await navigator.serviceWorker.getRegistration();
                const keys = await caches.keys();
                const cached = [];
                for (const k of keys) { for (const r of await (await caches.open(k)).keys()) cached.push(new URL(r.url).pathname.slice(1)); }
                return {isolated: self.crossOriginIsolated, sab: typeof SharedArrayBuffer !== 'undefined',
                        sw_registered: !!reg, sw_controller: !!navigator.serviceWorker.controller, cached};
            }""")
            if settle_sw:     # give the SW time to cache wasm/pck on first use
                for _ in range(40):
                    if {"index.wasm", "index.pck"} <= set(info["cached"]):
                        break
                    page.wait_for_timeout(250)
                    info["cached"] = page.evaluate("""async () => { const out=[]; for (const k of await caches.keys())
                        for (const r of await (await caches.open(k)).keys()) out.push(new URL(r.url).pathname.slice(1)); return out; }""")
        except Exception as exc:     # noqa: BLE001 — reported, not raised
            info, err = {}, f"{type(exc).__name__}: {exc}"
        finally:
            self.ctx.set_offline(False)
            page.close()
        text = "\n".join(logs)
        res = parse_output(text)
        return {"boot_ok": res.pop("_boot_ok"), "result": res, "page": info, "error": err, "offline": offline,
                "wall_s": round(time.time() - t0, 1), "log_tail": [ln for ln in logs if "FABRIC_RESULT" not in ln][-8:],
                "script_errors": len(re.findall(r"SCRIPT ERROR", text))}


def smoke(root: Path, log=print) -> dict[str, Any]:
    d = web_dir(root)
    out: dict[str, Any] = {}
    with LocalHost(d, isolation=True) as host, WebHarness() as wh:
        out["response_headers"] = {f: head_headers(host.url + f) for f in ("index.html", "index.wasm", "index.pck")}
        out["headers_ok"] = all(h.get("Cross-Origin-Opener-Policy") == "same-origin" and
                                h.get("Cross-Origin-Embedder-Policy") == "require-corp" for h in out["response_headers"].values())
        first = wh.run(host.url, ["--net-report"])               # installs the SW
        on = wh.run(host.url, ["--net-report"], settle_sw=True)  # SW-controlled: wasm/pck cached on use
        out["first_visit"] = {k: first[k] for k in ("boot_ok", "page", "error", "wall_s")}
        out["online"] = on
        off = wh.run(host.url, ["--net-report"], offline=True)   # network off: served from the SW cache
        out["offline_reload"] = off
    with LocalHost(d, isolation=False) as bare, WebHarness() as wh2:
        first = wh2.run(bare.url, ["--net-report"], timeout_s=60)
        # Godot's shell installs the SW and reloads itself when isolation is missing; the reloaded page is
        # isolated through the SW's header shim. Run again in the same profile to observe the steady state.
        second = wh2.run(bare.url, ["--net-report"], timeout_s=60)
        out["headerless_host"] = {"first": {k: first[k] for k in ("boot_ok", "page", "error")},
                                  "second": {k: second[k] for k in ("boot_ok", "page", "error")}}
    pg = on.get("page", {})
    out["checks"] = {
        "coop_coep_headers": out["headers_ok"],
        "cross_origin_isolated": bool(pg.get("isolated")) and bool(pg.get("sab")),
        "boots": on["boot_ok"] and on["script_errors"] == 0,
        "sw_registered": bool(pg.get("sw_registered")),
        "sw_cached_runtime": {"index.wasm", "index.pck", "index.html", "index.js"} <= set(pg.get("cached", [])),
        "offline_boot": off["boot_ok"] and bool(off.get("page", {}).get("sw_controller")),
        "net_dormant": bool((on["result"].get("net") or {}).get("offline_peer")),
        "headerless_host_isolated_via_sw": bool(second["boot_ok"] and second.get("page", {}).get("isolated")),
    }
    out["ok"] = all(out["checks"].values())
    log(f"PWA smoke: {out['checks']}")
    return out


def pwa_pipeline(root: Path, smoke_test: bool = True, log=print, **kw: Any) -> dict[str, Any]:
    if "smoke" in kw:
        smoke_test = kw["smoke"]
    d = web_dir(root)
    rep: dict[str, Any] = {"hook": patch_html(d)}
    (d / "_headers").write_text(HEADERS_FILE, encoding="utf-8")
    rep["budget"] = budget(d)
    rep["service_worker"] = sw_report(d)
    if smoke_test:
        try:
            rep["smoke"] = smoke(root, log=log)
        except Exception as exc:     # noqa: BLE001
            rep["smoke"] = {"ok": False, "error": f"{type(exc).__name__}: {exc}"}
    rep["ok"] = rep["hook"] and rep["budget"]["ok"] and rep["service_worker"]["ok"] and (rep.get("smoke", {}).get("ok", True))
    return rep
