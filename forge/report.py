"""Generate STATUS.md from the milestone registry + recorded acceptance results."""

from __future__ import annotations

from pathlib import Path

from forge import __milestone__, __version__
from forge.milestones import INCREMENTS, ORDER, recorded

PLAN = {
    "F0": "Manifest, forge CLI, asset store, orchestrator, telemetry schema",
    "F1": "Sprite/tile/DyeWorks procedural, gates, Godot binding, PatternVault, SwatchStudio",
    "F2": "Codegen (chars/abilities/stats), G1-Audio",
    "F3": "GIRT, CascadeHub, micro LM path, callouts",
    "F4": "Sandbox (bwrap/process tiers), atomic hot reload, snapshots + WAL, statecharts, guardian",
    "F5": "Monte Carlo balance (G-BAL-01) + Optuna tuning, soft-lock detection, versioned save migration, tier-3 boss",
    "F6": "Quest statechart, farming/gather/craft economy, tiered loot, adaptive music, cave ↔ open world; 15–20 min vertical slice",
    "F7": "Godot 4.3 exports (Linux, Windows, debug APK, Web PWA) via forge build --target, PWAPipeline (G-WEB-01), ShuttleLine multi-target contract, BoltPack SBOM + license audit",
}


def render(root: Path) -> str:
    lines = [
        "# STATUS.md — Milestone dashboard",
        "",
        "Generated by `forge report` from `forge/milestones.py` and `docs/acceptance-tests/results/`. Do not hand-edit.",
        "",
        f"**Package:** `{__version__}` · **Current Fabric milestone:** `{__milestone__}`",
        "",
        "| Fabric | Delivers | Game increment | Acceptance | Evidence |",
        "|---|---|---|---|---|",
    ]
    for m in ORDER:
        inc = INCREMENTS.get(m)
        rec = recorded(root, m)
        if rec is None:
            status = "not run" if inc else "not started"
        else:
            status = "✅ passed" if rec.get("passed") else "❌ failed"
        ev = f"[results/{m}.json](docs/acceptance-tests/results/{m}.json)" if rec else "—"
        lines.append(f"| {m} | {PLAN.get(m, '')} | {inc.increment if inc else '—'} | {status} | {ev} |")
    lines += ["", "Run `forge accept <F>` to (re)record a milestone; `forge report` to refresh this file.", ""]
    return "\n".join(lines)


def write(root: Path) -> Path:
    p = root / "STATUS.md"
    p.write_text(render(root), encoding="utf-8")
    return p
